export type Sector = (typeof SECTORS)[number];

export interface CardDefinition {
  id: string;
  ticker: string;
  company: string;
  /** Printed under the ticker, and the source of the card's fallback mark. */
  sector: Sector;
  tier: Tier;
  rarity: Rarity;
  /** Print number and run size, e.g. 24 of 420. */
  serial: number;
  runSize: number;
  /** Illustrative figures for the marketing site only. */
  price: number;
  change: number;
  /** Base colour of the card face. */
  accent: string;
  /** Optional second stop, which turns the face into a gradient. */
  accent2?: string;
  /**
   * The real Robinhood Chain Stock Token contract this card tracks —
   * verified against the issuer's own registry (chain id 4663), not a
   * synthetic ticker. This is a tokenized debt security issued by Robinhood
   * Assets (Jersey) Limited, not the underlying share, and its Chainlink
   * feed is what a live round would score against once wired up. See
   * https://docs.robinhood.com/chain/building-with-stock-tokens/.
   */
  contractAddress: `0x${string}`;
}

