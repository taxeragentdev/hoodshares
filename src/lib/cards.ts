import type { Rarity } from "./rarity";

/** Company size band, which drives how scarce a card's print run is. */
export type Tier = "mega" | "large" | "mid";

export const TIER_LABEL: Record<Tier, string> = {
  mega: "Mega Cap",
  large: "Large Cap",
  mid: "Mid Cap",
};

/**
 * Every sector a card can belong to.
 *
 * This is a closed list rather than a free string because each sector owns a
 * fallback mark in `src/components/marks/sectors.tsx`. Adding a sector here
 * without drawing its mark is a compile error, which is what guarantees a new
 * card can never render as a blank face.
 */
