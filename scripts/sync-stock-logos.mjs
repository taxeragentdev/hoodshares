#!/usr/bin/env node
/**
 * Pulls monochrome brand marks from simple-icons and writes
 * `src/components/marks/logos.generated.tsx`, keyed by ticker.
 *
 *   npm run logos:sync
 *
 * Tickers without a simple-icons slug stay in `marks/logos.custom.tsx`.
 * CardGlyph checks generated first, then custom, then the sector fallback.
 */

import { writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = resolve(ROOT, "src/components/marks/logos.generated.tsx");

/** ticker -> { slug, version }  — version is whichever simple-icons still
 *  ships that icon; a few well-known marks were dropped after v9. */
const ICONS = {
  TSLA: { slug: "tesla", version: 15 },
  NVDA: { slug: "nvidia", version: 15 },
  AAPL: { slug: "apple", version: 15 },
  AMZN: { slug: "amazon", version: 9 },
  MSFT: { slug: "microsoft", version: 9 },
  PLTR: { slug: "palantir", version: 15 },
  COIN: { slug: "coinbase", version: 15 },
  NFLX: { slug: "netflix", version: 15 },
  AMD: { slug: "amd", version: 15 },
  META: { slug: "meta", version: 15 },
  GOOGL: { slug: "google", version: 15 },
  INTC: { slug: "intel", version: 15 },
  SNAP: { slug: "snapchat", version: 15 },
  SHOP: { slug: "shopify", version: 15 },
  RBLX: { slug: "roblox", version: 15 },
  CRCL: { slug: "circle", version: 15 },
  SPCX: { slug: "spacex", version: 15 },
  BABA: { slug: "alibabadotcom", version: 15 },
  MSTR: { slug: "microstrategy", version: 15 },
};

function toJsx(svg) {
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1] ?? "0 0 24 24";
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"[^/]*\/>/g)].map(
    (m) => `      <path d="${m[1]}" fill="currentColor" />`,
  );
  if (paths.length === 0) throw new Error("no path in svg");
  return { viewBox, jsx: paths.join("\n") };
}

async function fetchIcon({ slug, version }) {
  const url = `https://cdn.jsdelivr.net/npm/simple-icons@${version}/icons/${slug}.svg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${slug} @${version}: ${res.status}`);
  return toJsx(await res.text());
}

const entries = [];
const failed = [];
for (const [ticker, spec] of Object.entries(ICONS)) {
  try {
    const mark = await fetchIcon(spec);
    entries.push({ ticker, ...mark, slug: spec.slug });
    console.log(`  ${ticker} ← ${spec.slug}`);
  } catch (error) {
    failed.push(`${ticker}: ${error.message}`);
  }
}

if (failed.length > 0) {
  console.error(failed.join("\n"));
  process.exit(1);
}

const body = `// Generated by scripts/sync-stock-logos.mjs — do not edit by hand.
// Brand marks from simple-icons (CC0). Remapped to currentColor.

import type { Mark } from "./types";

export const GENERATED_LOGOS: Record<string, Mark> = {
${entries
  .map(
    (e) => `  ${e.ticker}: {
    viewBox: "${e.viewBox}",
    node: (
      <>
${e.jsx}
      </>
    ),
  },`,
  )
  .join("\n")}
};
`;

await writeFile(OUTPUT, body + "\n");
console.log(`\nWrote ${OUTPUT.replace(ROOT + "/", "")} (${entries.length} logos)`);
